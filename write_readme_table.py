def main() -> None:
    conf = config.feishu_conf()
    client = FeishuClient(conf["app_id"], conf["app_secret"], conf["base_token"])
    headers = client._headers()
    base = f"https://open.feishu.cn/open-apis/bitable/v1/apps/{client.base_token}/tables"

    import requests

    # 已有同名表则删除重建（内容以脚本为准）
    resp = requests.get(base, headers=headers, params={"page_size": 100}, timeout=15).json()
    for t in resp.get("data", {}).get("items") or []:
        if t["name"] == TABLE_NAME:
            requests.delete(f"{base}/{t['table_id']}", headers=headers, timeout=15).json()
            print(f"  已删除旧版「{TABLE_NAME}」")

    resp = requests.post(base, headers=headers, timeout=15,
                         json={"table": {"name": TABLE_NAME,
                                         "fields": [{"field_name": "区块", "type": 1},
                                                    {"field_name": "内容", "type": 1}]}}).json()
    if resp.get("code") != 0:
        raise SystemExit(f"建表失败：code={resp.get('code')} {resp.get('msg')}")
    tid = resp["data"]["table_id"]

    for i, (section, body) in enumerate(SECTIONS, 1):
        client.create_record(tid, {"区块": f"{i}. {section}", "内容": body})
        print(f"  写入 {i}. {section}")

    print(f"\n完成 ✅ README 表已生成（{len(SECTIONS)} 个区块），位于多维表格最后一个标签页。")


if __name__ == "__main__":
    main()
